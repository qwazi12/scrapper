import { test, expect } from "@playwright/test";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
const evidence = path.resolve(__dirname, "../../artifacts/e2e");
const stack = JSON.parse(readFileSync(path.join(evidence, "stack.json"), "utf8"));
if (!stack.web.startsWith("http://127.0.0.1:") || !stack.api.startsWith("http://127.0.0.1:")) throw new Error("Local isolated E2E only");
const headers = { "x-access-token": stack.token };

test("Archive UI: complete inventory, verified bytes, interrupted upload, recovery and deduplication", async ({ page, context, request }) => {
  const isolation = await (await request.get(`${stack.api}/api/e2e/isolation`)).json();
  expect(isolation.safe_e2e_mode).toBe(true);
  expect(isolation.scheduler_threads).toEqual([]);
  await context.route("**/*", route => ["127.0.0.1", "localhost"].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  await page.addInitScript(({ api, token }) => { localStorage.setItem("scrapper_api_base", api); localStorage.setItem("scrapper_token", token); }, { api: stack.api, token: stack.token });
  const readEvidence = async () => (await request.get(`${stack.api}/api/e2e/archive-evidence`, { headers })).json();
  const before = await readEvidence();
  await page.goto("/#socialpilot/ingest");
  await expect(page.getByRole("heading", { name: "Channel archive to Google Drive" })).toBeVisible();
  await page.getByLabel("Archive channel URL").fill("https://www.youtube.com/@archive-fixture");
  await page.getByLabel("Archive Drive parent folder").fill("parent");
  await page.getByRole("button", { name: "Inventory complete channel", exact: true }).click();
  const channel = page.getByRole("article", { name: "Archive Original Archive Fixture" });
  await expect(channel.getByTestId("archive-counts")).toContainText("Discovered 63");
  await expect(channel.getByRole("button", { name: "Check storage capacity" })).toBeEnabled();
  await channel.getByRole("button", { name: "Check storage capacity" }).click();
  await expect(channel).toContainText("Drive available:");
  await request.post(`${stack.api}/api/e2e/archive-interrupt`, { headers });
  await channel.getByRole("button", { name: "Archive missing files" }).click();
  await expect(channel.getByTestId("archive-counts")).toContainText("Failed 1");
  await expect(channel).toContainText("transfer response lost");
  await page.reload();
  await channel.getByRole("button", { name: "Retry failures / resume" }).click();
  await expect(channel.getByTestId("archive-counts")).toContainText("Uploaded 63", { timeout: 120_000 });
  await expect(channel.getByTestId("archive-counts")).toContainText("Remaining 0");
  await expect(channel.getByRole("button", { name: "Archive missing files" })).toBeEnabled();
  const after = await readEvidence();
  expect(after.download_calls).toBe(63);
  expect(after.cloud_media_files).toBe(63);
  expect(after.checksummed_media_bytes).toBeGreaterThan(0);
  expect(after.queue_rows).toBe(before.queue_rows);
  expect(after.actual_drive_uploads).toBe(0);
  await channel.getByRole("button", { name: "Archive missing files" }).click();
  await expect(channel.getByRole("button", { name: "Archive missing files" })).toBeEnabled();
  expect((await readEvidence()).download_calls).toBe(63);
  const [download] = await Promise.all([page.waitForEvent("download"), channel.getByRole("button", { name: "Download channel manifest" }).click()]);
  await download.saveAs(path.join(evidence, "archive-channel-manifest.json"));
  await page.screenshot({ path: path.join(evidence, "archive-complete.png"), fullPage: true });
  writeFileSync(path.join(evidence, "archive-evidence.json"), JSON.stringify(await readEvidence(), null, 2));
});
